#!/usr/bin/env python3
"""Export original generated room/icon atlases to committed LVGL RGB565 assets."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parent
SOURCES={'rooms':ROOT/'source/rooms.png','icons':ROOT/'source/icons.png',
         'menu':ROOT/'../companion/source/icons.png','camp':ROOT/'../companion/source/camp.png'}

import sys
sys.path.insert(0,str(ROOT.parents[2]/'scripts'))
from rgb565_blocks import fold_2x,expand_2x

def encode(out):
    out.mkdir(parents=True,exist_ok=True)
    code=['/* Generated by build_assets.py; original PNGs and provenance retained. */','#include "theme_assets.h"']
    header=['#pragma once','#include "lvgl.h"'];records=[]
    def asset(name,source,w,h,crop=None,alpha=False):
        args=['magick',str(SOURCES[source])]
        if crop:args+=['-crop',crop,'+repage']
        if alpha:args+=['-channel','A','-threshold','50%','+channel','-trim','+repage','-sample',f'{w//2}x{h//2}','-gravity','center','-background','none','-extent',f'{w//2}x{h//2}']
        else:args+=['-sample',f'{w//2}x{h//2}!']
        args+=['-sample',f'{w}x{h}!','-depth','8','rgba:-']
        rgba=subprocess.check_output(args);assert len(rgba)==w*h*4
        data=bytearray()
        for i in range(0,len(rgba),4):
            r,g,b,_=rgba[i:i+4];data+=(((r>>3)<<11)|((g>>2)<<5)|(b>>3)).to_bytes(2,'little')
        if alpha:
            assert 0 in rgba[3::4] and 255 in rgba[3::4]
            data+=rgba[3::4]
        decoded=bytes(data);folded=not alpha and w==466 and h==466
        if folded:data=fold_2x(data,w,h);w//=2;h//=2
        code.append(f'_Alignas(4) static const uint8_t {name}_data[]={{')
        code.extend(['  '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24)])
        code.extend(['};',f'const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565'+('A8' if alpha else '')+f',.w={w},.h={h},.stride={w*2}}},.data_size=sizeof {name}_data,.data={name}_data}};'])
        header.append(f'extern const lv_image_dsc_t {name};')
        records.append(dict(name=name,bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),**(dict(storage='RGB565-2x2',decoded_sha256=hashlib.sha256(decoded).hexdigest()) if folded else {})))
    for i,name in enumerate(('pack','magic','rest','study')):
        asset('theme_room_'+name,'rooms',466,466,f'623x623+{(i%2)*627+2}+{(i//2)*627+2}')
    rows=[(0,502),(502,837),(837,1254)]
    names=['heart','shield','crystal','time','gear','usb','potion','bundle','hero','sun','notes','confirm']
    for i,name in enumerate(names):
        y,end=rows[i//4];x=round(i%4*1254/4);right=round((i%4+1)*1254/4)
        asset('theme_'+name,'icons',32,32,f'{right-x}x{end-y}+{x}+{y}',True)
        if name in ('heart','shield','confirm','crystal'):
            asset('theme_receipt_'+name,'icons',24,24,f'{right-x}x{end-y}+{x}+{y}',True)
    for i,name in enumerate(('sword','dice','magic','pack','rest','sheet')):
        asset('theme_'+name,'menu',32,32,f'418x627+{i%3*418}+{i//3*627}',True)
    asset('theme_camp_stage','camp',300,120,'1050x420+100+650')
    (out/'theme_assets.c').write_text('\n'.join(code)+'\n')
    (out/'theme_assets.h').write_text('\n'.join(header)+'\n')
    manifest=dict(images=records,image_bytes=sum(x['bytes'] for x in records),sources={k:hashlib.sha256(p.read_bytes()).hexdigest() for k,p in SOURCES.items()})
    (out/'assets.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Theme: {len(records)} images, {manifest["image_bytes"]} encoded bytes')

def verify():
    manifest=json.loads((ROOT/'assets.json').read_text())
    for key,digest in manifest['sources'].items():assert hashlib.sha256(SOURCES[key].read_bytes()).hexdigest()==digest
    arrays=dict(re.findall(r'const uint8_t (\w+)_data\[\]=\{(.*?)\};',(ROOT/'theme_assets.c').read_text(),re.S))
    assert len(arrays)==len(manifest['images'])
    for record in manifest['images']:
        data=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})',arrays[record['name']]))
        assert len(data)==record['bytes'] and hashlib.sha256(data).hexdigest()==record['sha256']
        if record.get('storage')=='RGB565-2x2':assert hashlib.sha256(expand_2x(data,233,233)).hexdigest()==record['decoded_sha256']
    assert sum(r['bytes'] for r in manifest['images'])==manifest['image_bytes']
    print('Theme source and raster hashes verified')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--verify',action='store_true');parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.verify:verify()
    elif args.check:
        verify()
        with tempfile.TemporaryDirectory() as folder:
            out=Path(folder);encode(out)
            for name in ('theme_assets.c','theme_assets.h','assets.json'):assert (out/name).read_bytes()==(ROOT/name).read_bytes()
    else:encode(ROOT)
