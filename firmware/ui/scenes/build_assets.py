#!/usr/bin/env python3
"""Export original generated scene panels to indexed pixels; never modifies source PNG."""
import argparse,hashlib,json,re,shutil,struct,subprocess,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parent
def export(out):
 magick=shutil.which('magick');assert magick,'ImageMagick 7 required only to export'
 source=ROOT/'source/environments.png'
 assert subprocess.check_output([magick,'identify','-format','%wx%h',str(source)],text=True)=='1774x887'
 bodies=['/* Generated by build_assets.py; do not edit. */','#include "scene_assets.h"'];records=[]
 for i in range(2):
  bmp=subprocess.check_output([magick,str(source),'-crop',f'887x887+{887*i}+0','+repage','-sample','233x233!','-alpha','off','-dither','None','-colors','128','-type','Palette','-depth','8','-compress','None','bmp3:-'])
  offset=struct.unpack_from('<I',bmp,10)[0];w,h=struct.unpack_from('<ii',bmp,18);bpp=struct.unpack_from('<H',bmp,28)[0]
  assert (w,h,bpp)==(233,233,8)
  count=struct.unpack_from('<I',bmp,46)[0] or 256;palette=bytearray(1024)
  for c in range(count):palette[c*4:c*4+4]=bmp[54+c*4:58+c*4][:3]+b'\xff'
  stride=(w+3)&~3;pixels=b''.join(bmp[offset+y*stride:offset+y*stride+w] for y in range(h-1,-1,-1));data=bytes(palette)+pixels
  bodies.append(f'static const uint8_t scene_{i+1}[]={{')
  for at in range(0,len(data),24):bodies.append(','.join(f'0x{x:02x}' for x in data[at:at+24])+',')
  bodies.append('};');records.append({'scene':i+1,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
 bodies.append('const uint8_t *const pd_scene_sources[2]={scene_1,scene_2};')
 out.mkdir(parents=True,exist_ok=True);(out/'scene_assets.c').write_text('\n'.join(bodies)+'\n')
 (out/'scene_assets.h').write_text('#pragma once\n#include <stdint.h>\nextern const uint8_t *const pd_scene_sources[2];\n')
 (out/'assets.json').write_text(json.dumps({'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'grid':[233,233],'images':records},indent=2)+'\n')
def verify():
 m=json.loads((ROOT/'assets.json').read_text());assert hashlib.sha256((ROOT/'source/environments.png').read_bytes()).hexdigest()==m['source_sha256']
 arrays=re.findall(r'static const uint8_t scene_\d+\[\]=\{(.*?)\};',(ROOT/'scene_assets.c').read_text(),re.S);assert len(arrays)==2
 for body,r in zip(arrays,m['images']):
  b=bytes(int(x,16) for x in re.findall('0x([0-9a-f]{2})',body));assert len(b)==r['bytes'] and hashlib.sha256(b).hexdigest()==r['sha256']
 print('Scene source and indexed assets verified (no image-generation/build dependency)')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--verify',action='store_true');p.add_argument('--check',action='store_true');a=p.parse_args()
 if a.verify:verify()
 elif a.check:
  verify()
  with tempfile.TemporaryDirectory() as d:
   export(Path(d))
   for name in ['scene_assets.c','scene_assets.h','assets.json']:assert (Path(d)/name).read_bytes()==(ROOT/name).read_bytes(),name
 else:export(ROOT)
