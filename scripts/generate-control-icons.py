#!/usr/bin/env python3
"""Deterministic original UI glyphs; no external image service or runtime allocation."""
import argparse,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'firmware/ui'
source=json.loads((root/'control-glyphs.json').read_text())
lines=['/* Generated by scripts/generate-control-icons.py from control-glyphs.json. */']
for name,rows in source['glyphs'].items():
    assert len(rows)==12 and all(len(r)==12 and set(r)<=set('.#') for r in rows)
    data=bytearray();alpha=bytearray()
    for y in range(24):
        color=int(source['palette']['highlight' if y<6 else 'ink'],16)
        r,g,b=color>>16,(color>>8)&255,color&255
        for x in range(24):
            data+=(((r>>3)<<11)|((g>>2)<<5)|(b>>3)).to_bytes(2,'little')
            alpha.append(255 if rows[y//2][x//2]=='#' else 0)
    data+=alpha
    lines.append(f'_Alignas(4) static const uint8_t {name}_pixels[]={{')
    lines+=[' '+','.join(str(b) for b in data[i:i+32])+',' for i in range(0,len(data),32)]
    lines+=['};',f'static const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.w=24,.h=24,.stride=48}},.data_size=sizeof {name}_pixels,.data={name}_pixels}};']
text='\n'.join(lines)+'\n'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
if args.check:assert (root/'control_icons.inc').read_text()==text,'Regenerate UI glyphs'
else:(root/'control_icons.inc').write_text(text)
print('UI control glyphs: seven original 12x12 masks, exact 2x pixels, static RGB565A8 checked')
