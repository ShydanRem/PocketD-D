#!/usr/bin/env python3
"""Generate original low-resolution d20 sprites. Standard library only, no remote assets.
An icosahedron is rasterized offline to a fixed 4-bit palette; firmware only blits.
"""
from itertools import combinations
from math import sqrt, sin, cos, pi
from pathlib import Path

SIZE=48
FRAMES=24
phi=(1+sqrt(5))/2
vertices=[(0,a,b*phi) for a in (-1,1) for b in (-1,1)]
vertices += [(a,b*phi,0) for a in (-1,1) for b in (-1,1)]
vertices += [(b*phi,0,a) for a in (-1,1) for b in (-1,1)]
def dot(a,b):return sum(x*y for x,y in zip(a,b))
def sub(a,b):return tuple(x-y for x,y in zip(a,b))
def cross(a,b):return (a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])
def unit(a):return tuple(x/sqrt(dot(a,a)) for x in a)
faces=[f for f in combinations(range(12),3) if all(abs(dot(sub(vertices[a],vertices[b]),sub(vertices[a],vertices[b]))-4)<1e-6 for a,b in combinations(f,2))]
assert len(faces)==20
front=faces[0]
z=unit(tuple(sum(vertices[i][j] for i in front) for j in range(3)))
y=unit(sub(vertices[front[0]],tuple(dot(vertices[front[0]],z)*v for v in z)))
x=unit(cross(y,z))
base=[(dot(v,x),-dot(v,y),dot(v,z)) for v in vertices]

def frame(index):
    angle=2*pi*index/FRAMES
    rotated=[]
    for x,y,z in base:
        # Oblique tumbling: both axes return exactly to the broad front face.
        xx=x*cos(angle)+z*sin(angle);zz=-x*sin(angle)+z*cos(angle)
        yy=y*cos(angle)+zz*sin(angle);zz=-y*sin(angle)+zz*cos(angle)
        rotated.append((xx,yy,zz))
    projected=[(23.5+x*11.5,23.5+y*11.5) for x,y,z in rotated]
    pixels=[0]*(SIZE*SIZE)
    def point(x,y,color):
        if 0<=x<SIZE and 0<=y<SIZE:pixels[y*SIZE+x]=color
    def edge(a,b,color):
        x,y=map(round,a);xx,yy=map(round,b)
        dx=abs(xx-x);sx=1 if x<xx else -1;dy=-abs(yy-y);sy=1 if y<yy else -1;err=dx+dy
        while True:
            point(x,y,color)
            if x==xx and y==yy:break
            e=2*err
            if e>=dy:err+=dy;x+=sx
            if e<=dx:err+=dx;y+=sy
    def triangle(a,b,c,color):
        def side(p,q,r):return (p[0]-r[0])*(q[1]-r[1])-(q[0]-r[0])*(p[1]-r[1])
        for yy in range(max(0,int(min(a[1],b[1],c[1]))),min(SIZE,int(max(a[1],b[1],c[1]))+2)):
            for xx in range(max(0,int(min(a[0],b[0],c[0]))),min(SIZE,int(max(a[0],b[0],c[0]))+2)):
                signs=[side((xx,yy),a,b),side((xx,yy),b,c),side((xx,yy),c,a)]
                if all(v>=0 for v in signs) or all(v<=0 for v in signs):point(xx,yy,color)
    for f in sorted(faces,key=lambda f:sum(rotated[i][2] for i in f)):
        coords=[rotated[i] for i in f]
        normal=unit(cross(sub(coords[1],coords[0]),sub(coords[2],coords[0])))
        centroid=tuple(sum(v[j] for v in coords)/3 for j in range(3))
        if dot(normal,centroid)<0:normal=tuple(-v for v in normal)
        if normal[2]<=0:continue
        light=dot(normal,unit((-0.6,-0.8,1.4)))
        shade=3 if light<0.05 else 4 if light<0.45 else 5 if light<0.8 else 6
        a,b,c=[projected[i] for i in f]
        triangle(a,b,c,shade)
        for p,q in [(a,b),(b,c),(c,a)]:edge(p,q,2)
    # Dark one-pixel silhouette and a small stepped specular highlight.
    original=pixels[:]
    for yy in range(SIZE):
        for xx in range(SIZE):
            if original[yy*SIZE+xx]:continue
            if any(0<=xx+dx<SIZE and 0<=yy+dy<SIZE and original[(yy+dy)*SIZE+xx+dx] for dx,dy in [(1,0),(-1,0),(0,1),(0,-1)]):point(xx,yy,1)
    return pixels

frames=[frame(i) for i in range(FRAMES)]
root=Path(__file__).resolve().parents[1]
out=root/'firmware/assets/d20_atlas.h'
lines=['/* Original PocketD-D pixel art. Generated by scripts/generate-dice.py. */', '#ifndef PD_D20_ATLAS_H','#define PD_D20_ATLAS_H',f'#define PD_D20_SIZE {SIZE}',f'#define PD_D20_FRAMES {FRAMES}', 'static const uint8_t pd_d20_atlas[PD_D20_FRAMES][PD_D20_SIZE*PD_D20_SIZE/2] = {']
for pixels in frames:
    packed=[(pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2)]
    lines.append('    {')
    for i in range(0,len(packed),32):lines.append('        '+','.join(f'0x{n:02x}' for n in packed[i:i+32])+',')
    lines.append('    },')
lines+=['};','#endif','']
content='\n'.join(lines)
if not out.exists() or out.read_text()!=content:
    out.write_text(content)
print(f'{out}: {FRAMES} frames, {FRAMES*SIZE*SIZE//2} flash bytes')
